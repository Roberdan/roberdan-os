#!/usr/bin/env python3
"""Generate the claude.ai and Cowork skills from ONE source (plan 2026-09-24 item 4.8).

Source: .github/skills/roberdan-twin/ (the portable twin skill, itself held to the canon by
test/test-twin-export-drift.sh). Each surface adds only what is specific to it, in an overlay
under bin/portable-skills/. Overlay directives, one per line:

    <!-- core: <heading> -->               the whole "## <heading>" section of the source SKILL.md
    <!-- core-block: <start> || <end> -->  source lines from <start> up to (not incl.) <end>
    <!-- replace: <old> || <new> -->       literal replacement over the finished page

    python3 bin/gen-portable-skills.py              regenerate in place
    python3 bin/gen-portable-skills.py --out DIR    write under DIR instead (drift test)

Uploading to claude.ai or Cowork stays Roberto's manual step: this only writes files.
"""

import argparse
import os
import re
import shutil
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, ".github", "skills", "roberdan-twin")
OVERLAYS = os.path.join(ROOT, "bin", "portable-skills")
SIDECARS = ("CONSTITUTION.md", "THINKING.md", "VOICE.md", "ENGINEERING.md")
TARGETS = {  # overlay -> (skill dir, sidecars copied from the source)
    "claude-ai.md": ("claude-ai-skill/roberto-mode", SIDECARS),
    "cowork.md": ("cowork-skill/roberdan", ()),  # VALUES/THINKING/ADVISORS stay Cowork-specific
}
BANNER = ("<!-- GENERATED by bin/gen-portable-skills.py from .github/skills/roberdan-twin/ + "
          "bin/portable-skills/{overlay}. Do not edit by hand: edit the source and regenerate. -->")
ZIP_DATE = (1980, 1, 1, 0, 0, 0)  # fixed: the same input always gives the same bytes


def section(src, heading):
    m = re.search(rf"^## {re.escape(heading)}\n.*?(?=^## |\Z)", src, re.MULTILINE | re.DOTALL)
    if not m:
        sys.exit(f"gen-portable-skills: la fonte non ha la sezione '## {heading}'")
    return m.group(0).rstrip("\n")


def block(src, start, end):
    lines = src.split("\n")
    i = next((n for n, line in enumerate(lines) if line.startswith(start)), None)
    j = next((n for n, line in enumerate(lines) if i is not None and n > i and line.startswith(end)), None)
    if i is None or j is None:
        sys.exit(f"gen-portable-skills: blocco '{start}' .. '{end}' non trovato nella fonte")
    text = "\n".join(lines[i:j]).rstrip("\n")
    return re.sub(r"^\*\*\d+\. ", "**", text)  # the step number belongs to the source's list


def render(overlay_name, src):
    with open(os.path.join(OVERLAYS, overlay_name), encoding="utf-8") as fh:
        overlay = fh.read()
    out, replaces = [], []
    for line in overlay.split("\n"):
        m = re.fullmatch(r"<!-- (core|core-block|replace): (.*) -->", line.strip())
        if not m:
            out.append(line)
        elif m.group(1) == "core":
            out.append(section(src, m.group(2)))
        elif m.group(1) == "core-block":
            out.append(block(src, *m.group(2).split(" || ", 1)))
        else:
            replaces.append(m.group(2).split(" || ", 1))
    page = "\n".join(out).rstrip("\n") + "\n"
    for old, new in replaces:
        if old not in page:
            sys.exit(f"gen-portable-skills: '{old}' non compare piu': aggiorna {overlay_name}")
        page = page.replace(old, new)
    fm_end = page.index("\n---\n", 4) + 5  # banner right after the frontmatter
    return page[:fm_end] + "\n" + BANNER.format(overlay=overlay_name) + "\n" + page[fm_end:]


def write_zip(skill_dir, zip_path):
    name = os.path.basename(skill_dir)
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_STORED) as zf:
        for fname in sorted(os.listdir(skill_dir)):
            if not fname.endswith(".md"):
                continue
            info = zipfile.ZipInfo(f"{name}/{fname}", date_time=ZIP_DATE)
            info.external_attr = 0o644 << 16
            with open(os.path.join(skill_dir, fname), "rb") as fh:
                zf.writestr(info, fh.read())


def main(argv=None):
    p = argparse.ArgumentParser(prog="gen-portable-skills")
    p.add_argument("--out", default=ROOT)
    p.add_argument("--source", default=SOURCE)
    args = p.parse_args(argv)
    with open(os.path.join(args.source, "SKILL.md"), encoding="utf-8") as fh:
        src = fh.read()
    for overlay, (rel, sidecars) in TARGETS.items():
        dest = os.path.join(args.out, rel)
        os.makedirs(dest, exist_ok=True)
        with open(os.path.join(dest, "SKILL.md"), "w", encoding="utf-8") as fh:
            fh.write(render(overlay, src))
        for sc in sidecars:
            shutil.copyfile(os.path.join(args.source, sc), os.path.join(dest, sc))
    claude = os.path.join(args.out, "claude-ai-skill", "roberto-mode")
    write_zip(claude, os.path.join(args.out, "claude-ai-skill", "roberto-mode.zip"))
    print("gen-portable-skills: generati claude-ai-skill/roberto-mode (+ roberto-mode.zip) e "
          "cowork-skill/roberdan/SKILL.md.")
    print("Il caricamento resta un passo manuale di Roberto: claude.ai -> Settings -> Skills -> "
          "Upload roberto-mode.zip; Cowork -> Personalizza -> Skill (o la cartella OneDrive).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
