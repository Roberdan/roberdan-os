#!/usr/bin/env bash
# pkgnet-guard.sh — when the corporate network blocks the public package
# registries, route every CLI package manager through the authorized
# pull-through proxy. On any other network this is a no-op.
#
# The block looks like a Microsoft Defender toast ("[TE] NPM URL Block") or a
# TLS reset (curl exit 35) on registry.npmjs.org / files.pythonhosted.org.
# The global ~/.npmrc, pip.conf and uv.toml already point at the proxy — but a
# project-local .npmrc that pins `registry=https://registry.npmjs.org/` (some
# OSS repos commit one for lockfile reproducibility) overrides them and hits
# the blocked host. An env var beats a project file, so that is what we set.
#
# This script writes ~/.config/roberdan-os/pkgnet.env with the exports;
# .zshenv sources it (one guarded line). When the public registries ARE
# reachable the probe deletes the file, so the guard vanishes on a clean
# machine and nothing has to be undone.
#
# The probe runs HERE (bootstrap / doctor / by hand) — never at shell startup.
#
# Usage:
#   bin/pkgnet-guard.sh            # probe the network, write or remove the env file
#   bin/pkgnet-guard.sh --check    # exit 0 = file matches reality, 1 = stale (for doctor)
#   bin/pkgnet-guard.sh --print    # print what the env file would contain, probe nothing
#   bin/pkgnet-guard.sh --quiet    # probe + apply, print only on change
set -euo pipefail

PROXY="${RDA_PKG_PROXY:-https://packagefeedproxy.microsoft.io}"
ENV_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/roberdan-os"
ENV_FILE="$ENV_DIR/pkgnet.env"
PUBLIC_HOSTS="registry.npmjs.org files.pythonhosted.org"

MODE="apply"
case "${1:-}" in
  --check) MODE="check" ;;
  --print) MODE="print" ;;
  --quiet) MODE="quiet" ;;
  -h|--help) sed -n '2,30p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
  "") ;;
  *) printf 'pkgnet-guard: unknown flag %s (try --help)\n' "$1" >&2; exit 2 ;;
esac

reachable() { curl -sS -o /dev/null --max-time 6 "https://$1/" >/dev/null 2>&1; }

# The proxy answers its /npm/ root with 404 — a 404 is still "reachable".
# curl returns non-zero only when the connection itself fails, so exit 0 here
# means the host responded at all.
proxy_up() { curl -sS -o /dev/null --max-time 6 "$PROXY/npm/" >/dev/null 2>&1; }

want_guard() {
  local blocked=1 h
  for h in $PUBLIC_HOSTS; do reachable "$h" || blocked=0; done
  [ "$blocked" -eq 0 ] || return 1
  proxy_up
}

render() {
  cat <<EOF
# generated by roberdan-os bin/pkgnet-guard.sh — do not edit by hand
# the public package registries are blocked on this network; route CLI package
# managers through the authorized proxy. Re-run bin/pkgnet-guard.sh to refresh.
export npm_config_registry="$PROXY/npm/"
export PIP_INDEX_URL="$PROXY/pypi/simple"
export UV_INDEX_URL="$PROXY/pypi/simple"
EOF
}

if [ "$MODE" = print ]; then
  render
  exit 0
fi

if want_guard; then
  DESIRED="$(render)"
  if [ "$MODE" = check ]; then
    [ -f "$ENV_FILE" ] && [ "$(cat "$ENV_FILE")" = "$DESIRED" ] && exit 0
    printf 'pkgnet-guard: env file is missing or stale — run bin/pkgnet-guard.sh\n' >&2
    exit 1
  fi
  mkdir -p "$ENV_DIR"
  if [ -f "$ENV_FILE" ] && [ "$(cat "$ENV_FILE")" = "$DESIRED" ]; then
    [ "$MODE" = quiet ] || printf 'pkgnet-guard: proxy route already in place (%s)\n' "$ENV_FILE"
  else
    printf '%s\n' "$DESIRED" > "$ENV_FILE"
    printf 'pkgnet-guard: public registries blocked — wrote proxy route to %s\n' "$ENV_FILE"
    printf '             add to ~/.zshenv (once):  [ -f %s ] && . %s\n' "$ENV_FILE" "$ENV_FILE"
  fi
else
  if [ "$MODE" = check ]; then
    [ ! -f "$ENV_FILE" ] && exit 0
    printf 'pkgnet-guard: public registries are reachable but the proxy override is still active — run bin/pkgnet-guard.sh\n' >&2
    exit 1
  fi
  if [ -f "$ENV_FILE" ]; then
    rm -f "$ENV_FILE"
    printf 'pkgnet-guard: public registries reachable — removed stale proxy route %s\n' "$ENV_FILE"
  else
    [ "$MODE" = quiet ] || printf 'pkgnet-guard: public registries reachable, no override needed\n'
  fi
fi
