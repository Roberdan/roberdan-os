#!/usr/bin/env bash
# bin/install-git-hooks.sh — installs the repo's native git hooks (.git/hooks is not
# versioned by git, so this is the step that wires hooks/pre-commit in).
# Idempotent: safe to re-run. Run this once per clone/worktree.
#
# It installs a SHIM, not a copy. It used to `cp`, and a copy is a photograph: on
# 2026-07-29 the installed pre-commit was still the 2 July version, so editing
# hooks/pre-commit changed nothing at all and the gate stayed green while the new check
# never ran. That is the worst kind of control — one you believe you have. A shim
# re-reads the versioned file on every commit, so the hook and its source cannot drift.
# The shim also fails LOUDLY (exit 1) if the source is gone, rather than letting commits
# through unchecked: hooks/pre-commit blocks on leak-check, so silently skipping it would
# turn a missing file into a confidentiality hole.
#
# With `--into <repo>` it installs a DIFFERENT hook (hooks/pre-commit-guest) into another
# repository. That mode exists because the mistake this repo learned from was not made
# here: on 2026-07-30 corporate directory data reached GitHub from a separate project. A
# hook installed only in the repo that never had the problem is a lock on the wrong door,
# so the check has to be able to travel to the repo that holds real data.
set -euo pipefail
# ROOT deve essere il CHECKOUT PRINCIPALE, mai il worktree da cui si lancia.
#
# Rilievo 2, 30 luglio 2026: questo script era stato eseguito da dentro
# `worktrees/roberdan-os/260730-092839`, quindi il percorso inciso nel controllo generato era
# quello. Quando quel worktree e' stato rimosso — la fine normale di una card — **ogni commit in
# roberdan-os si e' bloccato**: `pre-commit: BLOCCATO — .../260730-092839/hooks/pre-commit non
# esiste`. Il canone impone un worktree per card, quindi lanciarlo da li' e' il caso NORMALE, e
# il percorso che vi si incide e' garantito sparire.
#
# `--git-common-dir` e' la domanda giusta: in un worktree risponde `<principale>/.git`, nel
# checkout principale risponde `.git`. La cartella che lo contiene e' il checkout che sopravvive.
# Si CHIEDE a git dov'e' la casa, non la si deduce dalla posizione dello script — la stessa
# ragione per cui piu' sotto si usa `--git-path hooks` invece di ricostruire `.git/hooks`.
_script_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ROOT="$_script_root"
_common="$(git -C "$_script_root" rev-parse --path-format=absolute --git-common-dir 2>/dev/null || true)"
if [ -n "$_common" ] && [ -d "$_common" ]; then
  _main="$(dirname "$_common")"
  # Solo se laggiu' c'e' davvero questo repo: su un layout inatteso si resta dov'eravamo, invece
  # di incidere un percorso peggiore di quello che stiamo riparando.
  if [ -d "$_main/hooks" ] && [ -f "$_main/hooks/pre-commit" ]; then
    ROOT="$_main"
  fi
fi
[ "$ROOT" = "$_script_root" ] || \
  echo "install-git-hooks: lanciato da un worktree — incido il checkout principale $ROOT (il worktree sparira')"


if [ "${1:-}" = "--into" ]; then
  TARGET="${2:-}"
  [ -n "$TARGET" ] || { echo "install-git-hooks: --into richiede il path di un repo" >&2; exit 2; }
  TARGET="$(cd "$TARGET" 2>/dev/null && pwd)" || { echo "install-git-hooks: $2 non esiste" >&2; exit 2; }
  TARGET_GITDIR="$(git -C "$TARGET" rev-parse --git-dir 2>/dev/null)" \
    || { echo "install-git-hooks: $TARGET non e' un git repo" >&2; exit 2; }
  case "$TARGET_GITDIR" in /*) ;; *) TARGET_GITDIR="$TARGET/$TARGET_GITDIR" ;; esac
  if [ "$TARGET" = "$ROOT" ]; then
    echo "install-git-hooks: --into punta a roberdan-os stesso; usa il comando senza --into" >&2
    exit 2
  fi
  CHECK="$ROOT/test/directory-dump-check.sh"
  [ -f "$CHECK" ] || { echo "install-git-hooks: manca $CHECK" >&2; exit 2; }
  mkdir -p "$TARGET_GITDIR/hooks"
  DST="$TARGET_GITDIR/hooks/pre-commit"
  if [ -e "$DST" ] && ! grep -q 'GENERATED by bin/install-git-hooks.sh' "$DST" 2>/dev/null; then
    # Never silently replace a hook somebody else wrote: losing their check to install
    # ours would be the same class of harm this script exists to prevent.
    echo "install-git-hooks: $DST esiste gia' e non e' nostro — non lo tocco." >&2
    echo "  incorpora a mano:  bash \"$CHECK\" --staged" >&2
    exit 3
  fi
  {
    echo '#!/usr/bin/env bash'
    echo "# GENERATED by bin/install-git-hooks.sh --into — do not edit."
    echo "export DIRECTORY_DUMP_BASELINE=\"$TARGET_GITDIR/directory-dump-baseline\""
    sed -e "s|__CHECK_PATH__|$CHECK|" -e '1d' "$ROOT/hooks/pre-commit-guest"
  } > "$DST"
  chmod +x "$DST"
  # Freeze what the repository already carries, or the guard arrives red on a tree nobody
  # is about to change and gets bypassed on its first honest commit. The baseline lives
  # beside the hook inside .git/ — per clone, like the hook, and never in the project's
  # own files, which are not ours to add to.
  ( cd "$TARGET" && DIRECTORY_DUMP_BASELINE="$TARGET_GITDIR/directory-dump-baseline" \
      bash "$CHECK" --baseline ) || true
  echo "install-git-hooks: installed pre-commit -> $DST (guest, check -> $CHECK)"
  exit 0
fi

# `--git-path hooks` e non `--git-dir`/hooks, per la stessa ragione per cui
# test/validate.sh lo fa: in un WORKTREE git-dir e' .git/worktrees/<nome>, che non
# contiene hook e non ne avra' mai. Questo script scriveva la' e moriva con "No such
# file or directory" — quindi in un worktree il hook non veniva installato, e il canone
# impone un worktree per card: cioe' non veniva installato in nessun posto dove il
# lavoro avviene davvero. Si chiede a git DOVE guarda, non si ricostruisce il percorso.
# Fuori da un repo git questa riga moriva con l'errore grezzo di git ed exit 128 — vero prima di
# questa card, trovato dal test scritto per un'altra ragione. Un installatore che esce 128 con
# "fatal: not a git repository" fa cercare un problema di git a chi ha solo sbagliato cartella.
if ! HOOKDIR="$(git -C "$ROOT" rev-parse --git-path hooks 2>/dev/null)"; then
  echo "install-git-hooks: $ROOT non e' un repo git — non c'e' nessun posto dove installare." >&2
  echo "  Lancialo da dentro il repo, oppure usa --into <percorso-del-repo>." >&2
  exit 1
fi
case "$HOOKDIR" in /*) ;; *) HOOKDIR="$ROOT/$HOOKDIR" ;; esac

install_hook() {
  local name="$1" src="$ROOT/hooks/$1" dst="$HOOKDIR/$1"
  mkdir -p "$HOOKDIR"
  [ -f "$src" ] || { echo "install-git-hooks: skip $name (no hooks/$name in repo)"; return 0; }
  cat > "$dst" <<SHIM
#!/usr/bin/env bash
# GENERATED by bin/install-git-hooks.sh — do not edit. Edit hooks/$name instead.
# This is a shim on purpose: it re-reads the versioned hook every time, so an installed
# hook can never be an older version of the one in the repo.
if [ ! -f "$src" ]; then
  echo "pre-commit: BLOCCATO — $src non esiste (repo spostato?). Rilancia bin/install-git-hooks.sh" >&2
  exit 1
fi
exec bash "$src" "\$@"
SHIM
  chmod +x "$dst"
  echo "install-git-hooks: installed $name -> $dst (shim -> hooks/$name)"
}

install_hook pre-commit
