#!/usr/bin/env bash
# bin/install-git-hooks.sh — installs the repo's native git hooks (.git/hooks is not
# versioned by git, so this is the step that wires hooks/pre-commit in).
# Idempotent: safe to re-run. Run this once per clone/worktree.
#
# It installs a SHIM, not a copy. It used to `cp`, and a copy is a photograph: on
# 2026-07-29 the installed pre-commit was still the 2 July version, so editing
# hooks/pre-commit changed nothing at all and the gate stayed green while the new check
# never ran. That is the worst kind of control — one you believe you have. A shim
# re-reads the versioned file on every commit, so the hook and its source cannot drift.
# The shim also fails LOUDLY (exit 1) if the source is gone, rather than letting commits
# through unchecked: hooks/pre-commit blocks on leak-check, so silently skipping it would
# turn a missing file into a confidentiality hole.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
GITDIR="$(git -C "$ROOT" rev-parse --git-dir)"

install_hook() {
  local name="$1" src="$ROOT/hooks/$1" dst="$GITDIR/hooks/$1"
  [ -f "$src" ] || { echo "install-git-hooks: skip $name (no hooks/$name in repo)"; return 0; }
  cat > "$dst" <<SHIM
#!/usr/bin/env bash
# GENERATED by bin/install-git-hooks.sh — do not edit. Edit hooks/$name instead.
# This is a shim on purpose: it re-reads the versioned hook every time, so an installed
# hook can never be an older version of the one in the repo.
if [ ! -f "$src" ]; then
  echo "pre-commit: BLOCCATO — $src non esiste (repo spostato?). Rilancia bin/install-git-hooks.sh" >&2
  exit 1
fi
exec bash "$src" "\$@"
SHIM
  chmod +x "$dst"
  echo "install-git-hooks: installed $name -> $dst (shim -> hooks/$name)"
}

install_hook pre-commit
